// Numbers arrive formatted for the page's language, possibly in Arabic-Indic digits.
const value = (n: string | number) =>
  Number(
    String(n)
      .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x660))
      .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x6f0))
      .replace(/\D/g, ""),
  )

// Arabic's six plural forms; zero takes the `other` form unless given.
const plural = (
  n: string | number,
  f: { zero?: string; one: string; two: string; few: string; many: string; other: string },
) => {
  const v = value(n)
  const m = v % 100
  if (v === 0) return f.zero ?? f.other
  if (v === 1) return f.one
  if (v === 2) return f.two
  if (m >= 3 && m <= 10) return f.few
  if (m >= 11 && m <= 99) return f.many
  return f.other
}

